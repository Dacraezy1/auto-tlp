//! End-to-end tests that run the real binary. Hardware-dependent tests are skipped
//! automatically in sandboxes that have no /sys (e.g. the Nix build sandbox).
use std::collections::HashSet;
use std::path::Path;
use std::process::{Command, Output};

fn bin(args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_auto-tlp"))
        .args(args)
        .output()
        .expect("failed to run auto-tlp")
}

fn text(o: &Output) -> String {
    String::from_utf8_lossy(&o.stdout).into_owned()
}

fn has_sysfs() -> bool {
    Path::new("/sys/class").exists()
}

#[test]
fn version_matches_cargo() {
    let o = bin(&["--version"]);
    assert!(o.status.success());
    assert_eq!(
        text(&o).trim(),
        format!("auto-tlp {}", env!("CARGO_PKG_VERSION"))
    );
}

#[test]
fn help_lists_every_option() {
    let o = bin(&["--help"]);
    assert!(o.status.success());
    let t = text(&o);
    for opt in [
        "--profile",
        "--start-thresh",
        "--stop-thresh",
        "--output",
        "--install",
        "--report",
        "--verbose",
        "--terse",
        "--help",
        "--version",
    ] {
        assert!(t.contains(opt), "help is missing {opt}");
    }
}

#[test]
fn bad_arguments_exit_with_code_2() {
    for args in [
        &["--bogus"][..],
        &["--profile", "turbo"],
        &["--profile"],
        &["--start-thresh", "100"],
        &["--start-thresh", "abc"],
        &["--stop-thresh", "0"],
        &["--stop-thresh", "101"],
        &["--tlp-version", "abc"],
        &["--tlp-version"],
        &["--demo", "--install"],
        &["--apply"],
        &["--install", "--uninstall"],
        &["--against", "/tmp/x"],
        &["--diff", "--report"],
        &["--diff", "--install"],
        &["--only", "bogus"],
        &["--skip", "cpu,nonsense"],
        &["--format", "yaml"],
        &["--format", "nix", "--install"],
        &["--demo", "--format", "json", "--diff"],
    ] {
        let o = bin(args);
        assert_eq!(o.status.code(), Some(2), "args {args:?} should fail with 2");
        assert!(
            !String::from_utf8_lossy(&o.stderr).is_empty(),
            "args {args:?} should explain the error"
        );
    }
}

#[test]
fn report_runs() {
    if !has_sysfs() {
        return;
    }
    let o = bin(&["--report", "--verbose"]);
    assert!(o.status.success());
    let t = text(&o);
    for section in [
        "== Platform ==",
        "== CPU ==",
        "== Storage ==",
        "== Power management software ==",
    ] {
        assert!(t.contains(section), "report is missing {section}");
    }
}

#[test]
fn generates_valid_config_for_every_profile() {
    if !has_sysfs() {
        return;
    }
    for p in ["balanced", "performance", "battery"] {
        let o = bin(&["--profile", p]);
        assert!(o.status.success(), "profile {p}");
        let t = text(&o);
        assert!(t.starts_with("# TLP configuration generated by auto-tlp"));
        assert!(t.contains(&format!("# Profile   : {p}")));
        let mut seen = HashSet::new();
        for line in t.lines().filter(|l| !l.is_empty() && !l.starts_with('#')) {
            let (k, v) = line
                .split_once('=')
                .unwrap_or_else(|| panic!("bad line: {line}"));
            assert!(v.starts_with('"') && v.ends_with('"'), "unquoted: {line}");
            assert!(seen.insert(k.to_string()), "duplicate key {k}");
        }
        assert!(seen.contains("TLP_ENABLE"));
    }
}

#[test]
fn output_is_deterministic() {
    if !has_sysfs() {
        return;
    }
    let strip = |s: String| {
        s.lines()
            .filter(|l| !l.starts_with("# Generated"))
            .collect::<Vec<_>>()
            .join("\n")
    };
    assert_eq!(strip(text(&bin(&[]))), strip(text(&bin(&[]))));
}

#[test]
fn output_flag_writes_file() {
    if !has_sysfs() {
        return;
    }
    let path = std::env::temp_dir().join(format!("auto-tlp-test-{}.conf", std::process::id()));
    let o = bin(&["-o", path.to_str().unwrap(), "--terse"]);
    assert!(o.status.success());
    let written = std::fs::read_to_string(&path).expect("config file was not written");
    assert!(written.contains("TLP_ENABLE=\"1\""));
    let _ = std::fs::remove_file(&path);
}

