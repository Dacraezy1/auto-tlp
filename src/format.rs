//! Output formats: the native TLP `.conf`, a NixOS `services.tlp` module snippet, and JSON.
//! Both alternative formats are derived from the generated `.conf` text, so they always agree with it.

#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Format {
    #[default]
    Conf,
    Nix,
    Json,
}

impl Format {
    pub fn parse(s: &str) -> Option<Format> {
        match s.to_lowercase().as_str() {
            "conf" | "tlp" => Some(Format::Conf),
            "nix" | "nixos" => Some(Format::Nix),
            "json" => Some(Format::Json),
            _ => None,
        }
    }
}

pub fn render(format: Format, conf: &str) -> String {
    match format {
        Format::Conf => conf.to_string(),
        Format::Nix => to_nix(conf),
        Format::Json => to_json(conf),
    }
}

/// `KEY="value"` -> (KEY, value). Comments and anything else -> None.
fn setting(line: &str) -> Option<(&str, &str)> {
    let (k, v) = line.split_once('=')?;
    let valid = !k.is_empty()
        && k.chars()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
    valid.then(|| (k, v.trim_matches('"')))
}

fn nix_escape(v: &str) -> String {
    v.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace("${", "\\${")
}

fn json_escape(v: &str) -> String {
    let mut out = String::with_capacity(v.len());
    for c in v.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

/// A NixOS module snippet. `TLP_ENABLE` is left out: `services.tlp.enable` already provides it, and
/// defining it twice would be a conflicting definition.
pub fn to_nix(conf: &str) -> String {
    let mut out = String::from(
        "# Generated by auto-tlp. Merge this into your NixOS configuration.\n{\n  services.tlp = {\n    enable = true;\n    settings = {\n",
    );
    for line in conf.lines() {
        let l = line.trim_end();
        if l.is_empty() {
            out.push('\n');
        } else if let Some((k, v)) = setting(l) {
            if k != "TLP_ENABLE" {
                out.push_str(&format!("      {k} = \"{}\";\n", nix_escape(v)));
            }
        } else if let Some(comment) = l.strip_prefix('#') {
            // The header's "Install as /etc/tlp.d/..." hint is about the .conf format only.
            if !comment.trim_start().starts_with("Install as ") {
                out.push_str(&format!("      #{comment}\n")); // includes commented-out example keys
            }
        }
    }
    out.push_str("    };\n  };\n}\n");
    out
}

/// A flat JSON object of the active settings, in config order.
pub fn to_json(conf: &str) -> String {
    let items: Vec<String> = conf
        .lines()
        .filter_map(|l| setting(l.trim_end()))
        .map(|(k, v)| format!("  \"{}\": \"{}\"", k, json_escape(v)))
        .collect();
    if items.is_empty() {
        return "{}\n".to_string();
    }
    format!("{{\n{}\n}}\n", items.join(",\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    const CONF: &str = "# header\n\n# ===== CPU =====\nTLP_ENABLE=\"1\"\nCPU_BOOST_ON_PRF=\"1\"\n#MEM_SLEEP_ON_BAL=\"deep\"\nUSB_DENYLIST=\"046d:c52b 1234:5678\"\n";

    #[test]
    fn parse_names() {
        assert_eq!(Format::parse("NIX"), Some(Format::Nix));
        assert_eq!(Format::parse("nixos"), Some(Format::Nix));
        assert_eq!(Format::parse("tlp"), Some(Format::Conf));
        assert_eq!(Format::parse("json"), Some(Format::Json));
        assert_eq!(Format::parse("yaml"), None);
    }

    #[test]
    fn conf_is_passed_through() {
        assert_eq!(render(Format::Conf, CONF), CONF);
    }

    #[test]
    fn nix_output() {
        let n = to_nix(CONF);
        assert!(n.starts_with("# Generated by auto-tlp."));
        assert!(n.contains("services.tlp = {\n    enable = true;\n    settings = {\n"));
        assert!(n.contains("      CPU_BOOST_ON_PRF = \"1\";\n"));
        assert!(n.contains("      USB_DENYLIST = \"046d:c52b 1234:5678\";\n"));
        assert!(
            !n.contains("TLP_ENABLE"),
            "the module's enable option covers this"
        );
        assert!(
            n.contains("      #MEM_SLEEP_ON_BAL=\"deep\"\n"),
            "commented examples stay comments"
        );
        assert!(n.contains("      # ===== CPU =====\n"));
        assert!(
            !to_nix("# Install as /etc/tlp.d/x.conf, then run: sudo tlp start\nA=\"1\"\n")
                .contains("Install as")
        );
        assert!(n.ends_with("    };\n  };\n}\n"));
        // balanced braces
        assert_eq!(n.matches('{').count(), n.matches('}').count());
    }

    #[test]
    fn nix_escaping() {
        assert_eq!(nix_escape(r#"a"b\c${d}"#), r#"a\"b\\c\${d}"#);
    }

    #[test]
    fn json_output() {
        let j = to_json(CONF);
        assert_eq!(
            j,
            "{\n  \"TLP_ENABLE\": \"1\",\n  \"CPU_BOOST_ON_PRF\": \"1\",\n  \"USB_DENYLIST\": \"046d:c52b 1234:5678\"\n}\n"
        );
        assert_eq!(to_json("# only comments\n"), "{}\n");
    }

    #[test]
    fn json_escaping() {
        assert_eq!(json_escape("a\"b\\c\nd\u{1}"), "a\\\"b\\\\c\\nd\\u0001");
    }
}
