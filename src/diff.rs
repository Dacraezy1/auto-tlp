//! `--diff`: compare a freshly generated config with what is installed (or any other file).
//! Only active `KEY="value"` settings count; comments and blank lines are ignored.
use std::collections::{BTreeMap, BTreeSet};

/// Active settings of a TLP config.
pub fn parse(text: &str) -> BTreeMap<String, String> {
    text.lines()
        .filter_map(|l| {
            let l = l.trim();
            if l.is_empty() || l.starts_with('#') {
                return None;
            }
            let (k, v) = l.split_once('=')?;
            let k = k.trim();
            let valid = !k.is_empty()
                && k.chars()
                    .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
            valid.then(|| {
                (
                    k.to_string(),
                    v.trim().trim_matches(|c| c == '"' || c == '\'').to_string(),
                )
            })
        })
        .collect()
}

#[derive(Debug, PartialEq, Eq)]
pub enum Change {
    Added {
        key: String,
        value: String,
    },
    Removed {
        key: String,
        value: String,
    },
    Changed {
        key: String,
        old: String,
        new: String,
    },
}

/// Differences going from `old` to `new`, sorted by key.
pub fn compare(old: &BTreeMap<String, String>, new: &BTreeMap<String, String>) -> Vec<Change> {
    let keys: BTreeSet<&String> = old.keys().chain(new.keys()).collect();
    keys.into_iter()
        .filter_map(|k| match (old.get(k), new.get(k)) {
            (None, Some(v)) => Some(Change::Added {
                key: k.clone(),
                value: v.clone(),
            }),
            (Some(v), None) => Some(Change::Removed {
                key: k.clone(),
                value: v.clone(),
            }),
            (Some(a), Some(b)) if a != b => Some(Change::Changed {
                key: k.clone(),
                old: a.clone(),
                new: b.clone(),
            }),
            _ => None,
        })
        .collect()
}

pub fn render(changes: &[Change], old_label: &str) -> String {
    if changes.is_empty() {
        return format!("No differences: {old_label} already matches what auto-tlp generates.\n");
    }
    let mut out = format!("--- {old_label}\n+++ generated by auto-tlp\n");
    let (mut added, mut removed, mut changed) = (0, 0, 0);
    for c in changes {
        match c {
            Change::Added { key, value } => {
                added += 1;
                out.push_str(&format!("+ {key}=\"{value}\"\n"));
            }
            Change::Removed { key, value } => {
                removed += 1;
                out.push_str(&format!("- {key}=\"{value}\"\n"));
            }
            Change::Changed { key, old, new } => {
                changed += 1;
                out.push_str(&format!("~ {key}: \"{old}\" -> \"{new}\"\n"));
            }
        }
    }
    out.push_str(&format!(
        "\n{added} added, {removed} removed, {changed} changed\n"
    ));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const OLD: &str = "# comment\n\nTLP_ENABLE=\"1\"\nCPU_BOOST_ON_AC=\"1\"\nCPU_BOOST_ON_BAT=\"1\"\n#COMMENTED=\"x\"\nOLD_ONLY=\"y\"\n";
    const NEW: &str =
        "TLP_ENABLE=\"1\"\nCPU_BOOST_ON_AC=\"1\"\nCPU_BOOST_ON_BAT=\"0\"\nNEW_ONLY='z'\n";

    #[test]
    fn parse_keeps_only_active_settings() {
        let m = parse(OLD);
        assert_eq!(m.len(), 4);
        assert_eq!(m["CPU_BOOST_ON_BAT"], "1");
        assert!(!m.contains_key("COMMENTED"));
        assert_eq!(
            parse(NEW)["NEW_ONLY"],
            "z",
            "single quotes are stripped too"
        );
    }

    #[test]
    fn parse_ignores_garbage() {
        assert!(parse("not a setting\nlower_case=\"x\"\n=\"x\"\n").is_empty());
    }

    #[test]
    fn compare_finds_added_removed_changed() {
        let c = compare(&parse(OLD), &parse(NEW));
        assert_eq!(
            c,
            vec![
                Change::Changed {
                    key: "CPU_BOOST_ON_BAT".into(),
                    old: "1".into(),
                    new: "0".into()
                },
                Change::Added {
                    key: "NEW_ONLY".into(),
                    value: "z".into()
                },
                Change::Removed {
                    key: "OLD_ONLY".into(),
                    value: "y".into()
                },
            ]
        );
    }

    #[test]
    fn identical_configs_have_no_changes() {
        assert!(compare(&parse(NEW), &parse(NEW)).is_empty());
        // comments and ordering never matter
        assert!(compare(
            &parse("A=\"1\"\nB=\"2\"\n"),
            &parse("# hi\nB=\"2\"\nA=\"1\"\n")
        )
        .is_empty());
    }

    #[test]
    fn render_output() {
        let out = render(&compare(&parse(OLD), &parse(NEW)), "installed");
        assert!(out.starts_with("--- installed\n+++ generated by auto-tlp\n"));
        assert!(out.contains("~ CPU_BOOST_ON_BAT: \"1\" -> \"0\"\n"));
        assert!(out.contains("+ NEW_ONLY=\"z\"\n"));
        assert!(out.contains("- OLD_ONLY=\"y\"\n"));
        assert!(out.ends_with("1 added, 1 removed, 1 changed\n"));
        assert!(render(&[], "installed").starts_with("No differences"));
    }
}
